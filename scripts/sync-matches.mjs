// Regenerates utils/matches.ts from the @match lines of vendor/linkswift.user.js.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const source = readFileSync(new URL('vendor/linkswift.user.js', root), 'utf8');
const header = source.slice(0, source.indexOf('==/UserScript=='));
const matches = [...new Set([...header.matchAll(/^\/\/\s*@match\s+(\S+)/gm)].map((m) => m[1]))];
const version = header.match(/^\/\/\s*@version\s+(\S+)/m)?.[1];

writeFileSync(
  new URL('utils/matches.ts', root),
  `// Generated by scripts/sync-matches.mjs from the userscript's @match lines. Do not edit.\n` +
    `export const USERSCRIPT_VERSION = ${JSON.stringify(version)};\n\n` +
    `export const MATCHES = ${JSON.stringify(matches, null, 2)};\n`,
);
console.log(`Wrote ${matches.length} match patterns (userscript v${version}).`);
